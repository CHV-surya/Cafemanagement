import React, { useState, useMemo } from 'react'
import {
  PageHeader,
  StatCard,
  Button,
  Modal,
  StatusBadge,
} from '@/components/common'
import {
  WaiterAssignedTables,
  WaiterActiveOrders,
  WaiterRecentActivity,
  WaiterQuickActions,
} from '@/components/waiter'
import {
  OrderCreateModal,
  OrderDetailsModal,
  AddItemsToOrderModal,
} from '@/components/orders'
import { useAuthStore, useUIStore, useReservationStore, useOrderStore, timeToMinutes } from '@/store'
import { RestaurantTable } from '@/data/tableData'
import {
  getAssignedTablesForWaiter,
  getSectionNameForWaiter,
} from '@/data/waiterData'
import { Order } from '@/types/order'
import {
  Grid3X3,
  UtensilsCrossed,
  CheckCircle2,
  Receipt,
  Plus,
  Bell,
  Clock,
  IdCard,
  History,
} from 'lucide-react'

export const WaiterDashboardPage: React.FC = () => {
  const { currentUser } = useAuthStore()
  const { setNotificationDrawerOpen } = useUIStore()
  const { reservations } = useReservationStore()

  // Waiter identity - dynamic from auth session, never hardcoded
  const waiterId = currentUser?.id || 'WTR001'
  const waiterName = currentUser?.name || 'Sophie Dubois'
  const waiterSection = getSectionNameForWaiter(waiterId)

  // Centralized orders state from useOrderStore
  const { orders } = useOrderStore()

  // Modals & action states
  const [isNewOrderModalOpen, setIsNewOrderModalOpen] = useState(false)
  const [selectedTableForOrder, setSelectedTableForOrder] = useState<RestaurantTable | null>(null)
  const [isHistoryModalOpen, setIsHistoryModalOpen] = useState(false)
  const [inspectedOrder, setInspectedOrder] = useState<Order | null>(null)
  const [orderForAddingItems, setOrderForAddingItems] = useState<Order | null>(null)

  // Current formatted date and time
  const currentDateTimeFormatted = useMemo(() => {
    const now = new Date()
    const datePart = now.toLocaleDateString('en-US', {
      weekday: 'short',
      month: 'short',
      day: 'numeric',
    })
    const timePart = now.toLocaleTimeString('en-US', {
      hour: 'numeric',
      minute: '2-digit',
      hour12: true,
    })
    return `${datePart} • ${timePart}`
  }, [])

  // 1. Data Isolation: Filter tables strictly assigned to this waiter
  const myAssignedTables = useMemo(() => {
    return getAssignedTablesForWaiter(waiterId)
  }, [waiterId])

  // 2. Data Isolation: Filter orders strictly assigned to this waiter
  const myOrders = useMemo(() => {
    return orders.filter((o) => o.waiterId === waiterId)
  }, [orders, waiterId])

  // Active orders (pending, preparing, ready)
  const myActiveOrders = useMemo(() => {
    return myOrders.filter(
      (o) => o.status === 'pending' || o.status === 'preparing' || o.status === 'ready'
    )
  }, [myOrders])

  // Completed orders today
  const myCompletedOrders = useMemo(() => {
    return myOrders.filter((o) => o.status === 'completed')
  }, [myOrders])

  // Ready orders awaiting server delivery
  const myReadyOrders = useMemo(() => {
    return myOrders.filter((o) => o.status === 'ready')
  }, [myOrders])

  // Today's total sales generated by this waiter
  const myTotalSales = useMemo(() => {
    return myCompletedOrders.reduce((sum, o) => sum + o.totalAmount, 0)
  }, [myCompletedOrders])

  // Table breakdown calculation
  const tableBreakdown = useMemo(() => {
    const todayStr = new Date().toISOString().split('T')[0]
    const nowMinutes = new Date().getHours() * 60 + new Date().getMinutes()

    let occupied = 0
    let reserved = 0
    let available = 0

    myAssignedTables.forEach((table) => {
      const hasActiveOrder = myActiveOrders.some((o) => o.tableId === table.id)
      const todayRes = reservations.find(
        (r) => r.tableId === table.id && r.date === todayStr && r.status !== 'cancelled'
      )

      if (hasActiveOrder) {
        occupied += 1
      } else if (todayRes) {
        const resMinutes = timeToMinutes(todayRes.time)
        if (Math.abs(nowMinutes - resMinutes) < 90) {
          occupied += 1
        } else {
          reserved += 1
        }
      } else {
        available += 1
      }
    })

    return { occupied, reserved, available, total: myAssignedTables.length }
  }, [myAssignedTables, myActiveOrders, reservations])

  // Handlers
  const handleTakeOrderFromTable = (table: RestaurantTable) => {
    setSelectedTableForOrder(table)
    setIsNewOrderModalOpen(true)
  }

  const scrollToTables = () => {
    const el = document.getElementById('assigned-tables-section')
    if (el) el.scrollIntoView({ behavior: 'smooth' })
  }

  const scrollToOrders = () => {
    const el = document.getElementById('active-orders-section')
    if (el) el.scrollIntoView({ behavior: 'smooth' })
  }

  return (
    <div className="space-y-8 text-left pb-10">
      {/* 1. Waiter Dashboard Header */}
      <PageHeader
        title="Floor Service Terminal"
        subtitle={`Welcome, ${waiterName}. Here is your assigned section status and active tickets.`}
        breadcrumbs={[
          { label: 'Staff' },
          { label: 'Waiter Terminal' },
        ]}
        actions={
          <div className="flex flex-wrap items-center gap-2.5">
            {/* Live Clock / Date */}
            <span className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-xl bg-cream border border-cream-border text-xs font-semibold text-secondary-text shadow-2xs">
              <Clock className="w-3.5 h-3.5 text-gold-dark" />
              <span>{currentDateTimeFormatted}</span>
            </span>

            {/* Waiter ID Pill */}
            <span className="hidden sm:inline-flex items-center gap-1.5 px-3 py-1.5 rounded-xl bg-gold/15 text-burgundy-dark border border-gold/30 text-xs font-semibold">
              <IdCard className="w-4 h-4 text-gold-dark" />
              <span>Server ID: <strong className="font-mono">{waiterId}</strong></span>
            </span>

            {/* Notification Drawer Trigger */}
            <Button
              variant="outline"
              size="sm"
              onClick={() => setNotificationDrawerOpen(true)}
              leftIcon={<Bell className="w-3.5 h-3.5 text-gold-dark" />}
              className="py-1.5 px-3 text-xs"
            >
              Notifications
            </Button>

            {/* Quick Take Order CTA */}
            <Button
              variant="gold"
              size="sm"
              onClick={() => {
                setSelectedTableForOrder(null)
                setIsNewOrderModalOpen(true)
              }}
              leftIcon={<Plus className="w-4 h-4" />}
              className="shadow-gold text-xs py-1.5"
            >
              New Ticket
            </Button>
          </div>
        }
      />

      {/* 2. Overview Statistics (4 Cards) */}
      <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-4 gap-4">
        {/* Card 1: My Assigned Tables */}
        <StatCard
          title="My Assigned Tables"
          value={`${tableBreakdown.total} Tables`}
          change={{
            value: `${tableBreakdown.occupied} Seated`,
            isPositive: tableBreakdown.occupied > 0,
            label: `${tableBreakdown.available} available`,
          }}
          description={waiterSection}
          icon={Grid3X3}
        />

        {/* Card 2: Active Orders */}
        <StatCard
          title="Active Orders"
          value={`${myActiveOrders.length} Orders`}
          change={{
            value: `${myReadyOrders.length} Ready`,
            isPositive: myReadyOrders.length === 0,
            label: "for hot pass",
          }}
          description={`${myActiveOrders.length - myReadyOrders.length} currently firing in kitchen`}
          icon={UtensilsCrossed}
        />

        {/* Card 3: Completed Orders Today */}
        <StatCard
          title="Completed Orders Today"
          value={`${myCompletedOrders.length} Orders`}
          change={{
            value: "100%",
            isPositive: true,
            label: "fulfillment rate",
          }}
          description="Average turnaround: 21 min"
          icon={CheckCircle2}
        />

        {/* Card 4: Today's Sales */}
        <StatCard
          title="Today's Sales"
          value={`₹${myTotalSales.toLocaleString('en-IN')}`}
          change={{
            value: `₹${myCompletedOrders.length ? Math.round(myTotalSales / myCompletedOrders.length).toLocaleString('en-IN') : '0'}`,
            isPositive: true,
            label: "avg ticket",
          }}
          description={`Across ${myCompletedOrders.length} settled checks`}
          icon={Receipt}
        />
      </div>

      {/* 6. Quick Actions Section */}
      <WaiterQuickActions
        onScrollToTables={scrollToTables}
        onScrollToOrders={scrollToOrders}
        onOpenNewOrder={() => {
          setSelectedTableForOrder(null)
          setIsNewOrderModalOpen(true)
        }}
        onOpenHistory={() => setIsHistoryModalOpen(true)}
      />

      {/* 3. Assigned Tables Section */}
      <WaiterAssignedTables
        waiterId={waiterId}
        waiterName={waiterName}
        orders={orders}
        onTakeOrder={handleTakeOrderFromTable}
        onViewOrder={(order) => setInspectedOrder(order)}
      />

      {/* Two Column Layout: Active Orders (Left 7 Cols) & Recent Activity (Right 5 Cols) */}
      <div className="grid grid-cols-1 lg:grid-cols-12 gap-8 items-start">
        {/* 4. Active Orders Overview */}
        <div className="lg:col-span-7">
          <WaiterActiveOrders
            waiterId={waiterId}
            waiterName={waiterName}
            orders={orders}
            onViewOrder={(order) => setInspectedOrder(order)}
          />
        </div>

        {/* 5. Recent Activity Panel */}
        <div className="lg:col-span-5">
          <WaiterRecentActivity
            waiterId={waiterId}
            waiterName={waiterName}
          />
        </div>
      </div>

      {/* Create New Order Modal */}
      <OrderCreateModal
        isOpen={isNewOrderModalOpen}
        onClose={() => {
          setIsNewOrderModalOpen(false)
          setSelectedTableForOrder(null)
        }}
        userRole="waiter"
        waiterId={waiterId}
        waiterName={waiterName}
        defaultTableId={selectedTableForOrder?.id}
      />

      {/* Order History Modal */}
      {isHistoryModalOpen && (
        <Modal
          isOpen={isHistoryModalOpen}
          onClose={() => setIsHistoryModalOpen(false)}
          title={
            <div className="flex items-center gap-2">
              <History className="w-5 h-5 text-gold-dark" />
              <span className="font-display text-lg font-bold text-burgundy-dark">
                Shift Order History (Server: {waiterName})
              </span>
            </div>
          }
          size="lg"
          footer={
            <div className="flex items-center justify-between w-full">
              <span className="text-xs text-secondary-text">
                Total Settled: ₹{myTotalSales.toLocaleString('en-IN')} across {myCompletedOrders.length} tickets
              </span>
              <Button
                variant="primary"
                size="sm"
                onClick={() => setIsHistoryModalOpen(false)}
              >
                Close History
              </Button>
            </div>
          }
        >
          <div className="space-y-3 text-left text-xs max-h-[60vh] overflow-y-auto pr-1">
            {myOrders.filter((o) => o.status === 'completed' || o.status === 'cancelled').length === 0 ? (
              <p className="text-secondary-text py-6 text-center">
                No settled or closed orders recorded yet for this shift.
              </p>
            ) : (
              myOrders
                .filter((o) => o.status === 'completed' || o.status === 'cancelled')
                .map((order) => (
                  <div
                    key={order.id}
                    onClick={() => {
                      setIsHistoryModalOpen(false)
                      setInspectedOrder(order)
                    }}
                    className="p-3.5 rounded-xl bg-cream/40 border border-cream-border flex items-center justify-between gap-3 hover:bg-cream-card transition-colors cursor-pointer"
                  >
                    <div>
                      <div className="flex items-center gap-2">
                        <span className="font-mono font-bold text-burgundy-dark">{order.id}</span>
                        <span className="font-bold text-main-text">• {order.tableNumber || order.orderType}</span>
                        <StatusBadge status={order.status} />
                      </div>
                      <p className="text-[11px] text-secondary-text mt-0.5">
                        {order.customerName} • {order.itemsSummary}
                      </p>
                    </div>

                    <div className="text-right shrink-0">
                      <p className="font-display text-sm font-bold text-burgundy-dark">
                        ₹{order.totalAmount.toLocaleString('en-IN')}
                      </p>
                      <p className="text-[10px] text-secondary-text">{order.orderTime}</p>
                    </div>
                  </div>
                ))
            )}
          </div>
        </Modal>
      )}

      {/* Canonical Order Details Modal */}
      {inspectedOrder && (
        <OrderDetailsModal
          isOpen={!!inspectedOrder}
          onClose={() => setInspectedOrder(null)}
          order={orders.find((o) => o.id === inspectedOrder.id) || inspectedOrder}
          userRole="waiter"
          staffId={waiterId}
          staffName={waiterName}
          onOrderUpdated={() => {
            // Updated directly in useOrderStore
          }}
          onAddMoreItems={(order) => {
            setOrderForAddingItems(order)
          }}
        />
      )}

      {/* Add Items to Existing Active Order Modal */}
      {orderForAddingItems && (
        <AddItemsToOrderModal
          isOpen={!!orderForAddingItems}
          onClose={() => setOrderForAddingItems(null)}
          order={orders.find((o) => o.id === orderForAddingItems.id) || orderForAddingItems}
          staffId={waiterId}
          staffName={waiterName}
        />
      )}
    </div>
  )
}
